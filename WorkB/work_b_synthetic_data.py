import numpy as np
import pandas as pd
from scipy import stats

# -----------------------------
# 1. Basic settings
# -----------------------------

np.random.seed(42)

n = 120
n_group = 60


# -----------------------------
# 2. Create participant profiles
# -----------------------------

data = pd.DataFrame({
    "pitch": np.random.choice(["low", "high"], n),
    "tempo": np.random.choice(["slow", "fast"], n),
    "beat": np.random.choice(["weak", "strong"], n),
    "mode": np.random.choice(["minor", "major"], n)
})


# -----------------------------
# 3. Assign matched / mismatched conditions
# -----------------------------

data["condition"] = ["matched"] * n_group + ["mismatched"] * n_group
data["condition"] = np.random.permutation(data["condition"])


# -----------------------------
# 4. Simulate initial liking scores
# -----------------------------

data["liking"] = np.where(
    data["condition"] == "matched",
    np.random.normal(65, 15, n),
    np.random.normal(55, 15, n)
)

# Keep scores between 0 and 100
data["liking"] = np.clip(data["liking"], 0, 100)

print(data.head())

print("\nGroup summary:")
print(data.groupby("condition")["liking"].agg(["mean", "std", "count"]))

# -----------------------------
# 5. Welch independent-samples t-test
# -----------------------------

matched = data[data["condition"] == "matched"]["liking"]
mismatched = data[data["condition"] == "mismatched"]["liking"]

t_stat, p_value = stats.ttest_ind(
    matched,
    mismatched,
    equal_var=False
)

observed_diff = matched.mean() - mismatched.mean()

print("Matched mean:", matched.mean())
print("Mismatched mean:", mismatched.mean())
print("Mean difference:", observed_diff)
print("t-statistic:", t_stat)
print("p-value:", p_value)


# -----------------------------
# 6. Permutation test
# -----------------------------

scores = data["liking"].to_numpy()

n_perm = 10000
permuted_diffs = []

for i in range(n_perm):
    shuffled = np.random.permutation(scores)

    fake_matched = shuffled[:n_group]
    fake_mismatched = shuffled[n_group:]

    fake_diff = fake_matched.mean() - fake_mismatched.mean()
    permuted_diffs.append(fake_diff)

permuted_diffs = np.array(permuted_diffs)

permutation_p = np.mean(
    np.abs(permuted_diffs) >= np.abs(observed_diff)
)

print("\nPermutation test")
print("Observed mean difference:", observed_diff)
print("Permutation p-value:", permutation_p)